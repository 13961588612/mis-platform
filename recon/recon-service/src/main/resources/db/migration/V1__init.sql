-- ============================================================================
-- recon-service 平台库 DDL 初始化迁移（Flyway V1）
-- ----------------------------------------------------------------------------
-- 文件来源：《对账平台V3-开发任务分解.md》§三（Oracle 12c DDL，139~475 行）
--           → PostgreSQL 方言转换
-- 转换依据：《对账平台V3-接入MIS技术适配.md》§2.1（方言对照）/ §2.2（CLOB→JSONB 归类）
-- 规格文档：《T02-spec.md》§2 全局转换规则与类型映射（锁定）、§3 逐表转换规格、
--           §4 JSONB/TEXT 归类、§5 索引与 CHECK 约束总清单（唯一执行依据）
-- 转换日期：2026-08-14
-- 转换要点：
--   VARCHAR2(n CHAR)      → VARCHAR(n)              （PG 按字符计长，中文安全，不写 (n CHAR)）
--   NUMBER(20) 金额列      → BIGINT                  （全部 *_cent 列，整数分）
--   NUMBER 计数/秒/天/量值 → INTEGER                 （计数/序号/秒数/天数/量值）
--   NUMBER(1) 布尔         → SMALLINT（保持 0/1，JPA Integer 映射）
--   CLOB（JSON 语义）      → JSONB（A 类 21 列 + B 类裁定 4 列 = 25 列；JSONB 列不设默认值）
--   CLOB / VARCHAR2(2000) 长文本 → TEXT（key_scan_sql/agg_sql/gate_sql/content/err_msg/diff_desc/remark，防超长截断）
--   DATE（含时分秒）       → TIMESTAMP（无时区，Asia/Shanghai）；唯一例外 recon_source_record.biz_date 取日语义用 DATE
--   SYSDATE               → now()（默认值 DEFAULT now()）
--   GENERATED BY DEFAULT AS IDENTITY → BIGSERIAL（19 张含 id 表；recon_seq_watermark 无 id，主键 ds_code 保持原样）
--   CREATE SEQUENCE CACHE 1000 NOORDER → CACHE 100（PG CACHE=每会话预取，勿照抄 1000；PG 天然 NOORDER）
-- 字段注释逐条沿用任务分解原文（方言翻译不丢注释）；表间区块分隔注释沿用规格 §3 命名
-- ============================================================================

-- ============ 0. 全局序列（台账 update_seq 与全库单调发号共用） ============
CREATE SEQUENCE recon_update_seq START WITH 1 INCREMENT BY 1 CACHE 100;
-- CACHE 100: 批量发号（PG 每会话预取，勿照抄 Oracle 1000）；正确性由 recon_seq_watermark 水位表保证
-- 发号：SELECT nextval('recon_update_seq')；台账 upsert 用 nextval('recon_update_seq')（技术适配 §2.3）

-- ============ 1. recon_connection 连接（被对账的业务库） ============
CREATE TABLE recon_connection (
    id                BIGSERIAL PRIMARY KEY,
    conn_code         VARCHAR(64)  NOT NULL,   -- 连接编码，唯一，snake_case，保存后不可改
    name              VARCHAR(128),            -- 名称
    type              VARCHAR(32)  NOT NULL,   -- 业务库类型：mysql/oracle/postgresql（决定分页方言）
    jdbc_url          VARCHAR(512),            -- JDBC URL（必填，由 host/port+database/service_name 拼装）
    username          VARCHAR(128),            -- 只读账号
    password          VARCHAR(256),            -- 明文存库（内网决策，只读账号兜底）
    props_json        JSONB,                   -- 连接池/超时等通用高级配置（B 类裁定，§4.2）
    db_timezone       VARCHAR(64) DEFAULT 'Asia/Shanghai' NOT NULL, -- 源库时区
    fetch_overlap_sec INTEGER DEFAULT 300 NOT NULL,  -- 窗口重叠秒数（连接级默认，ds 可覆盖）
    clock_probe_sql   VARCHAR(200),            -- 时钟探针 SQL（mysql: SELECT NOW(3); oracle: SELECT SYSTIMESTAMP FROM DUAL）
    jdbc_props_locked VARCHAR(500),            -- 平台强制注入并锁定的 JDBC 参数
    enabled           SMALLINT DEFAULT 1 NOT NULL, -- 启用状态
    created_at        TIMESTAMP DEFAULT now() NOT NULL,
    updated_at        TIMESTAMP DEFAULT now() NOT NULL
);
CREATE UNIQUE INDEX uk_conn_code ON recon_connection(conn_code);

-- ============ 2. recon_datasource 数据源（定义一次，到处引用） ============
CREATE TABLE recon_datasource (
    id                    BIGSERIAL PRIMARY KEY,
    ds_code               VARCHAR(64)  NOT NULL,  -- 数据源编码 {库简称}_{表名}，唯一
    name                  VARCHAR(128),           -- 名称
    conn_code             VARCHAR(64),            -- 引用连接；api 类型可空
    pull_cron             VARCHAR(64),            -- 拉取调度 cron
    record_key_expression VARCHAR(256) NOT NULL,  -- 源行唯一标识模板表达式 {f1}_{f2}（三层键·存储层）
    time_field            VARCHAR(64),            -- 业务时间字段，写台账 record_time
    fetch_type            VARCHAR(16) DEFAULT 'db' NOT NULL, -- db/api/custom（MVP 只实现 db）
    fetch_config_json     JSONB,                  -- sql/fetch_one_sql/fetch_mode/fetch_time_field/biz_time_field/api 配置
    fields_json           JSONB,                  -- 字段映射与注释 [{name,source,annotation,is_sensitive}]
    health_rules_json     JSONB,                  -- 健康度阈值（row_count_delta_pct/null_rate_threshold/allow_empty/deletion_detect）
    amount_fields_json    JSONB,                  -- 字段级金额声明 {field:{unit(yuan/point),role(primary/aux),sign_rule,direction}}（补丁01/02）
    refund_sign_rule      VARCHAR(16),            -- same_table_negative/same_table_type_col/separate_table/none
    refund_flag_expr      VARCHAR(200),           -- same_table_type_col 时的退款判定表达式
    grain                 VARCHAR(16) DEFAULT 'row' NOT NULL, -- row/aggregated（MVP 只用 row）
    group_by_fields       VARCHAR(256),           -- grain=aggregated 时必填（MVP 预留）
    member_key_field      VARCHAR(64),            -- 聚合成员键（MVP 预留）
    key_scan_sql          TEXT,                   -- 两阶段拉取阶段一，必须含 :p_start/:p_end（MVP 预留）
    agg_sql               TEXT,                   -- 两阶段拉取阶段二，禁含窗口参数（MVP 预留）
    agg_key_batch_size    INTEGER DEFAULT 500 NOT NULL, -- 聚合键批大小 1~1000（Oracle IN 硬限制）
    agg_join_mode         VARCHAR(16) DEFAULT 'in_list' NOT NULL, -- in_list/temp_table
    agg_full_recompute_cron VARCHAR(64),          -- 物理删除兜底全域重算 cron
    mixed_direction       SMALLINT DEFAULT 0 NOT NULL, -- 同表混合销售与退款=1
    direction_key_field   VARCHAR(64),            -- mixed_direction=1 时必填，record_key 强制拼接
    key_case_mode         VARCHAR(8) DEFAULT 'upper' NOT NULL, -- upper/none（MySQL *_ci 用 upper；Oracle 用 none）
    delete_mode           VARCHAR(16) DEFAULT 'unknown' NOT NULL, -- unknown/none/soft/physical（第一批 5 ds 均 none）
    soft_delete_expr      VARCHAR(200),           -- delete_mode=soft 时必填
    delete_mode_evidence  VARCHAR(200),           -- 删除语义确认证据（谁/何时/依据）
    enabled               SMALLINT DEFAULT 1 NOT NULL,
    created_at            TIMESTAMP DEFAULT now() NOT NULL,
    updated_at            TIMESTAMP DEFAULT now() NOT NULL
);
CREATE UNIQUE INDEX uk_ds_code ON recon_datasource(ds_code);
ALTER TABLE recon_datasource ADD CONSTRAINT ck_ds_grain    CHECK (grain='row' OR group_by_fields IS NOT NULL);
ALTER TABLE recon_datasource ADD CONSTRAINT ck_ds_batch    CHECK (agg_key_batch_size BETWEEN 1 AND 1000);
ALTER TABLE recon_datasource ADD CONSTRAINT ck_ds_case     CHECK (key_case_mode IN ('upper','none'));
ALTER TABLE recon_datasource ADD CONSTRAINT ck_ds_del_mode CHECK (delete_mode IN ('unknown','none','soft','physical'));
ALTER TABLE recon_datasource ADD CONSTRAINT ck_ds_del_expr CHECK (delete_mode <> 'soft' OR soft_delete_expr IS NOT NULL);
ALTER TABLE recon_datasource ADD CONSTRAINT ck_ds_mixed_key CHECK (mixed_direction = 0 OR direction_key_field IS NOT NULL);

-- ============ 3. recon_scenario 场景 ============
CREATE TABLE recon_scenario (
    id             BIGSERIAL PRIMARY KEY,
    scenario_code  VARCHAR(64) NOT NULL,       -- 场景编码，唯一
    name           VARCHAR(128),
    cron_expr      VARCHAR(64),                -- 对账触发 cron
    uses_json      JSONB,                      -- 派生的数据源引用（由 check 参与数据源自动汇总）：ds + alias + use_fields（alias 场景级唯一，默认=ds_code 可改短；use_fields 由比较字段并集自动生成）
    hooks_json     JSONB,                      -- after_fetch 加工（MVP 支持 aggregate_group，第一版可不配）
    reporter_json  JSONB,                      -- 兼容期报告渠道（新配置用 recon_reporter_config）
    report_cron    VARCHAR(64),                -- ReportRunner 触发 cron（与对账解耦）
    report_type    VARCHAR(16) DEFAULT 'diff' NOT NULL, -- diff/balance/both（MVP 只实现 diff）
    pool_max_age_days INTEGER DEFAULT 30,      -- 未平差异池账龄上限
    pending_max_wait_hours INTEGER DEFAULT 24, -- pending 最长等待，超时强制 confirmed（两轮确认条件②）
    on_degraded    VARCHAR(16) DEFAULT 'proceed', -- 健康闸门：proceed/block
    on_empty       VARCHAR(16) DEFAULT 'proceed',
    on_error       VARCHAR(16) DEFAULT 'proceed',
    enabled        SMALLINT DEFAULT 1 NOT NULL,
    created_at     TIMESTAMP DEFAULT now() NOT NULL,
    updated_at     TIMESTAMP DEFAULT now() NOT NULL
);
CREATE UNIQUE INDEX uk_scenario_code ON recon_scenario(scenario_code);

-- ============ 4. recon_check 检查（一个场景多个 check） ============
CREATE TABLE recon_check (
    id             BIGSERIAL PRIMARY KEY,
    scenario_code  VARCHAR(64) NOT NULL,
    check_name     VARCHAR(128) NOT NULL,      -- 创建后不可修改（差异身份组成部分）
    seq_no         INTEGER DEFAULT 0,          -- 执行顺序
    consume_json   JSONB,                      -- 检查级消费模式 {alias:{mode,incremental/time_window,start,end}}（time_field 可省略，默认取数据源声明的 time_field；start/end 由 check 级汇总窗口配置自动回写，行内可省略）
    run_mode       VARCHAR(8) DEFAULT 'formal' NOT NULL, -- formal/observe（observe=差异落库但报告静音）
    enabled        SMALLINT DEFAULT 1 NOT NULL,
    created_at     TIMESTAMP DEFAULT now() NOT NULL,
    updated_at     TIMESTAMP DEFAULT now() NOT NULL
);
CREATE UNIQUE INDEX uk_check ON recon_check(scenario_code, check_name);

-- ============ 5. recon_match_rule 匹配规则（匹配键唯一定义处，三层键·匹配层） ============
CREATE TABLE recon_match_rule (
    id             BIGSERIAL PRIMARY KEY,
    scenario_code  VARCHAR(64) NOT NULL,
    check_name     VARCHAR(128) NOT NULL,
    strategy       VARCHAR(32) NOT NULL,       -- exact_key/composite_key/sum_check/chain/custom/custom_check
    datasets_json  JSONB,                      -- 参与匹配的 alias 列表（B 类裁定，§4.2）
    key_fields_json JSONB,                     -- 匹配键字段：模板表达式（对象形式按数据集声明，如 orders: "{order_no}_{pay_channel}"；列表 [order_no] 仅同名单字段兼容等价，见 T09 增量子任务）
    field_transform_json JSONB,                -- 字段值归一（per check，三层键·归一层）：[{dataset,field,type,pattern,replacement}]
    multi_row_json JSONB,                      -- 同键多行策略 {alias: aggregate/latest/reject}，默认 reject
    custom_class   VARCHAR(256),               -- custom/chain 全限定类名（MVP 预留）
    config_json    JSONB,                      -- chain 跳数/custom 参数（MVP 预留）
    created_at     TIMESTAMP DEFAULT now() NOT NULL,
    updated_at     TIMESTAMP DEFAULT now() NOT NULL
);
CREATE UNIQUE INDEX uk_match_rule ON recon_match_rule(scenario_code, check_name);

-- ============ 6. recon_compare_rule 比较规则 ============
CREATE TABLE recon_compare_rule (
    id             BIGSERIAL PRIMARY KEY,
    scenario_code  VARCHAR(64) NOT NULL,
    check_name     VARCHAR(128) NOT NULL,
    rules_json     JSONB,                      -- fields:[{name,left_field,right_field,compare_mode(equal/lte/gte/lt/gt/contains/regex),tolerance,is_amount,value_transform}]；tolerance 单位=分（整数）（B 类裁定，§4.2）
    created_at     TIMESTAMP DEFAULT now() NOT NULL,
    updated_at     TIMESTAMP DEFAULT now() NOT NULL
);
CREATE UNIQUE INDEX uk_compare_rule ON recon_compare_rule(scenario_code, check_name);

-- ============ 7. recon_readiness_gate 数据就绪门（补丁02 §3.7.4，关联用 scenario_code） ============
CREATE TABLE recon_readiness_gate (
    id              BIGSERIAL PRIMARY KEY,
    scenario_code   VARCHAR(64) NOT NULL,      -- 关联场景
    gate_name       VARCHAR(128) NOT NULL,     -- 如 wechat_bill_ready / pos_daily_settle_done
    gate_type       VARCHAR(16) NOT NULL,      -- flag_query/row_count_delta/app_callback/stability_window
    gate_sql        TEXT,                      -- flag_query(返回0/1)/row_count_delta 判定 SQL
    gate_config_json JSONB,                    -- 阈值/时间窗口/超时（stability_window_min/max_delta/timeout）
    min_wait_min    INTEGER DEFAULT 0 NOT NULL,     -- 就绪后至少等待
    max_wait_min    INTEGER DEFAULT 120 NOT NULL,   -- 最大等待，超时降级（仅软前置）
    enabled         SMALLINT DEFAULT 1 NOT NULL,
    created_at      TIMESTAMP DEFAULT now() NOT NULL,
    updated_at      TIMESTAMP DEFAULT now() NOT NULL
);
CREATE INDEX idx_gate_scenario ON recon_readiness_gate(scenario_code);
ALTER TABLE recon_readiness_gate ADD CONSTRAINT ck_gate_type CHECK (gate_type IN ('flag_query','row_count_delta','app_callback','stability_window'));

-- ============ 8. recon_reporter_config 报告渠道（check 级路由） ============
CREATE TABLE recon_reporter_config (
    id            BIGSERIAL PRIMARY KEY,
    scenario_code VARCHAR(64) NOT NULL,
    check_name    VARCHAR(128) DEFAULT '*' NOT NULL, -- '*' = 该场景全部 check
    channel       VARCHAR(64) NOT NULL,        -- email/webhook/custom
    config_json   JSONB,                       -- 收件人/URL/自定义 Reporter class 及参数
    min_severity  VARCHAR(16) DEFAULT 'info' NOT NULL, -- info/warn/critical，只投递 >= 此级别
    enabled       SMALLINT DEFAULT 1 NOT NULL,
    created_at    TIMESTAMP DEFAULT now() NOT NULL,
    updated_at    TIMESTAMP DEFAULT now() NOT NULL
);
CREATE INDEX idx_reporter_scenario ON recon_reporter_config(scenario_code, check_name);

-- ============ 9. recon_source_record 源数据台账（V3 核心，(ds_code,record_key) 唯一，拉取 upsert） ============
CREATE TABLE recon_source_record (
    id           BIGSERIAL PRIMARY KEY,
    ds_code      VARCHAR(64)  NOT NULL,
    record_key   VARCHAR(256) NOT NULL,        -- 源行唯一标识（三层键·存储层）
    record_data  JSONB NOT NULL,               -- 整行数据 JSON（值一律字符串存储，金额原始值可回溯）
    record_time  TIMESTAMP,                    -- 业务时间（ds.time_field）
    biz_date     DATE,                         -- 业务日 TRUNC(record_time)，报表归属，MVP 可空（PG 纯日期语义）
    update_seq   BIGINT NOT NULL,              -- 版本号：每次 upsert/逻辑删除取 recon_update_seq.NEXTVAL
    is_deleted   SMALLINT DEFAULT 0 NOT NULL,  -- 逻辑删除标记（tombstone）
    deleted_at   TIMESTAMP,                    -- 删除时间
    amount_cent  BIGINT,                       -- 标准化主金额：整数分带符号（补丁01/02 一等公民列）
    amount_raw   VARCHAR(64),                  -- 源库原始金额值（字符串，可回溯，原始态只读）
    amount_direction VARCHAR(8),               -- in(收)/out(付)/none(非资金行)
    last_pull_run_id BIGINT,                   -- 最近写入它的拉取运行
    created_at   TIMESTAMP DEFAULT now() NOT NULL,
    updated_at   TIMESTAMP DEFAULT now() NOT NULL -- 写入时间（应用层维护）
);
CREATE UNIQUE INDEX uk_source_record ON recon_source_record(ds_code, record_key);
CREATE INDEX idx_source_seq  ON recon_source_record(ds_code, update_seq);   -- 游标增量扫描
CREATE INDEX idx_source_time ON recon_source_record(ds_code, record_time);  -- time_window 汇总扫描
CREATE INDEX idx_source_amount ON recon_source_record(ds_code, biz_date, amount_cent); -- 汇总/平衡表

-- ============ 10. recon_pull_run 拉取运行记录 ============
CREATE TABLE recon_pull_run (
    id            BIGSERIAL PRIMARY KEY,
    ds_code       VARCHAR(64) NOT NULL,
    window_start  TIMESTAMP,                   -- 本次拉取窗口（业务库 update_time 区间）
    window_end    TIMESTAMP,
    row_count     INTEGER DEFAULT 0,           -- 拉取行数
    insert_count  INTEGER DEFAULT 0,           -- upsert 新增
    update_count  INTEGER DEFAULT 0,           -- upsert 更新
    health_status VARCHAR(16),                 -- healthy/degraded/empty/error（4.4）
    health_detail_json JSONB,                  -- 健康度各项指标实测值
    readiness_passed   SMALLINT DEFAULT 0 NOT NULL, -- 就绪门通过
    readiness_degraded SMALLINT DEFAULT 0 NOT NULL, -- 超时降级（稳定窗口兜底）
    readiness_log      JSONB,                  -- 各 gate 检查结果 JSON（B 类裁定，§4.2）
    clock_skew_ms  INTEGER,                    -- 实测源库−平台毫秒
    status        VARCHAR(16) DEFAULT 'running' NOT NULL, -- running/success/failed
    err_msg       TEXT,
    started_at    TIMESTAMP DEFAULT now() NOT NULL,
    finished_at   TIMESTAMP
);
CREATE INDEX idx_pull_run_ds ON recon_pull_run(ds_code, started_at);

-- ============ 11. recon_seq_watermark 已提交安全水位（发号顺序≠提交顺序的正确性保证） ============
CREATE TABLE recon_seq_watermark (
    ds_code       VARCHAR(64) PRIMARY KEY,
    committed_seq BIGINT NOT NULL DEFAULT 0,   -- 已提交安全水位，ReconRunner 只能消费到此处
    updated_at    TIMESTAMP DEFAULT now() NOT NULL
);

-- ============ 12. recon_consume_cursor 消费游标（场景+检查+数据源 → 高水位，per-check 粒度） ============
CREATE TABLE recon_consume_cursor (
    id             BIGSERIAL PRIMARY KEY,
    scenario_code  VARCHAR(64) NOT NULL,
    check_name     VARCHAR(128) NOT NULL,      -- per-check 粒度
    ds_code        VARCHAR(64) NOT NULL,
    cursor_seq     BIGINT DEFAULT 0 NOT NULL,  -- 已消费到的最大 update_seq
    updated_at     TIMESTAMP DEFAULT now() NOT NULL
);
CREATE UNIQUE INDEX uk_cursor ON recon_consume_cursor(scenario_code, check_name, ds_code);

-- ============ 13. recon_detail 差异明细（差异身份唯一，状态就地流转；matched 不落明细写 matched_index） ============
CREATE TABLE recon_detail (
    id             BIGSERIAL PRIMARY KEY,
    scenario_code  VARCHAR(64)  NOT NULL,
    check_name     VARCHAR(128) NOT NULL,      -- 原始检查名
    pair_segment   VARCHAR(64) DEFAULT '-' NOT NULL, -- chain 拆解段名（orders-pays），非 chain 固定 '-'（唯一索引 NULL!=NULL 必须 NOT NULL）
    match_key_hash VARCHAR(64) NOT NULL,       -- 匹配键 SHA-256 哈希（身份列；sum_check 用 record_key 哈希；anomaly 空键用 __nullkey__:ds:record_key）
    match_key_display VARCHAR(512),            -- 匹配键可读值（展示用）
    diff_type      VARCHAR(32)  NOT NULL,      -- unmatched_left/unmatched_right/field_mismatch/anomaly（可流转）
    status         VARCHAR(16)  NOT NULL,      -- pending/confirmed/resolved/deferred（可流转）
    defer_until    TIMESTAMP,                  -- deferred 到期时间（pre_match 抑制）
    pending_peer_pull_run_id BIGINT,           -- 首次 pending 时对端 max(pull_run_id WHERE ds=pending_peer_ds_code AND status='success')（两轮确认条件①）
    pending_peer_ds_code VARCHAR(64),          -- 对端数据源编码（两轮确认"对端"身份）
    pending_at     TIMESTAMP,                  -- 首次 pending 时间（条件②，超时强制 confirmed）
    left_data_json  JSONB,                     -- 差异证据（左侧台账原始值，不经归一）
    right_data_json JSONB,                     -- 差异证据（右侧台账原始值，不经归一）
    diff_desc      TEXT,                       -- 中文摘要（见 §18.4）
    diff_amount_cent BIGINT,                   -- 整数分（补丁01 P-2；is_amount 字段比较差值 |left-right|，取第一个差异金额）
    diff_diagnosis_json JSONB,                 -- 差异诊断 JSON（匹配/比较/判定三阶段，限 32KB）
    handle_status  VARCHAR(16) DEFAULT 'unhandled' NOT NULL, -- unhandled/handled/ignored/false_positive（人工轴，引擎不覆盖）
    reported_at    TIMESTAMP,                  -- 已报告时间（防重发，仅投递成功后回填）
    reopen_seq     INTEGER DEFAULT 0 NOT NULL, -- 重开世代（resolved→confirmed +1，防指纹去重抑制）
    resolved_at    TIMESTAMP,                  -- 配平出池时间
    first_seen_at  TIMESTAMP DEFAULT now() NOT NULL, -- 首次发现时间（账龄基准，不变）
    updated_at     TIMESTAMP DEFAULT now() NOT NULL -- 最后流转时间
);
CREATE UNIQUE INDEX uk_detail_identity ON recon_detail(scenario_code, check_name, pair_segment, match_key_hash);
CREATE INDEX idx_detail_pool   ON recon_detail(scenario_code, check_name, status, handle_status, first_seen_at); -- 池扫描
CREATE INDEX idx_detail_report ON recon_detail(scenario_code, status, reported_at);   -- 报告扫描
ALTER TABLE recon_detail ADD CONSTRAINT ck_detail_status CHECK (status IN ('pending','confirmed','resolved','deferred'));
ALTER TABLE recon_detail ADD CONSTRAINT ck_detail_handle CHECK (handle_status IN ('unhandled','handled','ignored','false_positive'));

-- ============ 14. recon_detail_source_ref 差异↔台账行锚（池还原与反查依据） ============
