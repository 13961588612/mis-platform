CREATE UNIQUE INDEX uk_detail_ref ON recon_detail_source_ref(detail_id, side, ds_code, record_key);
CREATE INDEX idx_ref_source ON recon_detail_source_ref(ds_code, record_key);

-- ============ 15. recon_run 对账运行记录 ============
CREATE TABLE recon_run (
    id             BIGSERIAL PRIMARY KEY,
    scenario_code  VARCHAR(64) NOT NULL,
    matched_count  INTEGER DEFAULT 0,          -- 匹配且一致（不落明细，仅计数）
    diff_count     INTEGER DEFAULT 0,          -- 本轮新增/流转差异
    resolved_count INTEGER DEFAULT 0,          -- 本轮配平出池
    consumed_seq_json JSONB,                   -- 本轮每(check,ds)消费到最大 update_seq + time_window 执行追踪
    status         VARCHAR(16) DEFAULT 'running' NOT NULL, -- running/success/failed/skipped
    err_msg        TEXT,
    started_at     TIMESTAMP DEFAULT now() NOT NULL,
    finished_at    TIMESTAMP
);
CREATE INDEX idx_run_scenario ON recon_run(scenario_code, started_at);

-- ============ 16. recon_diff_handle 人工处理记录（独立表，重对不丢人工标记） ============
CREATE TABLE recon_diff_handle (
    id            BIGSERIAL PRIMARY KEY,
    detail_id     BIGINT NOT NULL,             -- 关联 recon_detail.id
    handle_status VARCHAR(16) NOT NULL,        -- handled/ignored/false_positive
    operator      VARCHAR(64),
    remark        TEXT,
    handled_at    TIMESTAMP DEFAULT now() NOT NULL
);
CREATE INDEX idx_handle_detail ON recon_diff_handle(detail_id);

-- ============ 17. recon_matched_index 已配平索引（match_key_hash→record_key 轻量映射，防单边重拉误报） ============
CREATE TABLE recon_matched_index (
    id            BIGSERIAL PRIMARY KEY,
    scenario_code VARCHAR(64) NOT NULL,
    check_name    VARCHAR(128) NOT NULL,
    pair_segment  VARCHAR(64) DEFAULT '-' NOT NULL,
    match_key_hash VARCHAR(64) NOT NULL,       -- 与 recon_detail.match_key_hash 一致
    match_key_display VARCHAR(512),
    ds_code       VARCHAR(64) NOT NULL,
    record_key    VARCHAR(256) NOT NULL,
    record_time   TIMESTAMP,                   -- 用于 30 天清理
    created_at    TIMESTAMP DEFAULT now() NOT NULL
);
CREATE UNIQUE INDEX uk_matched_idx ON recon_matched_index(scenario_code, check_name, pair_segment, match_key_hash, ds_code, record_key);
CREATE INDEX idx_matched_lookup ON recon_matched_index(scenario_code, check_name, pair_segment, match_key_hash); -- 回查索引

-- ============ 18. recon_report_run 报告运行记录（报告线独立调度） ============
CREATE TABLE recon_report_run (
    id             BIGSERIAL PRIMARY KEY,
    scenario_code  VARCHAR(64) NOT NULL,
    report_type    VARCHAR(16) NOT NULL,       -- diff/balance/both
    diff_count     INTEGER DEFAULT 0,          -- 本报告含差异数
    send_status    VARCHAR(16) NOT NULL,       -- success/failed/partial
    err_msg        TEXT,
    started_at     TIMESTAMP DEFAULT now() NOT NULL,
    finished_at    TIMESTAMP
);
CREATE INDEX idx_report_run_scenario ON recon_report_run(scenario_code, started_at);

-- ============ 19. recon_alert_log 告警发送留痕（去重/限流/复盘依据；运维告警也写此表） ============
CREATE TABLE recon_alert_log (
    id            BIGSERIAL PRIMARY KEY,
    scenario_code VARCHAR(64),
    check_name    VARCHAR(128),
    detail_ids_json JSONB,                     -- 关联差异 detail_id 列表（审计追溯）
    severity      VARCHAR(16) DEFAULT 'info',  -- info/warn/critical（分级投递）
    channel       VARCHAR(64),                 -- email/webhook/ops（运维通道）
    fingerprint   VARCHAR(256),                -- 内容指纹（去重，含 reopen_seq）
    content       TEXT,
    send_status   VARCHAR(16),                 -- success/failed
    retry_count   INTEGER DEFAULT 0,
    sent_at       TIMESTAMP DEFAULT now() NOT NULL
);
CREATE INDEX idx_alert_fp ON recon_alert_log(fingerprint, sent_at);
CREATE INDEX idx_alert_detail ON recon_alert_log(scenario_code, check_name, sent_at);

-- ============ 20. recon_backlog_window 欠账窗口（time_window 检查被 skip 时兜底补算） ============
CREATE TABLE recon_backlog_window (
