-- V170：技能池独立分类树（邻接表）+ 技能绑定
-- PostgreSQL 16 | 幂等
-- 分类真值在平台库，不写在 Skill.category 字符串里。
-- deny-unmapped=true：须登记 sys_api + sys_menu_api

CREATE TABLE IF NOT EXISTS ai_skill_category (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id   BIGINT NOT NULL DEFAULT 0,
    name        VARCHAR(128) NOT NULL,
    sort_order  INTEGER NOT NULL DEFAULT 0,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

COMMENT ON TABLE ai_skill_category IS '技能池分类树（parent_id=0 为根）';

CREATE INDEX IF NOT EXISTS idx_ai_skill_category_parent
    ON ai_skill_category (parent_id, sort_order, id);

CREATE TABLE IF NOT EXISTS ai_skill_category_bind (
    skill_id     VARCHAR(128) PRIMARY KEY,
    category_id  BIGINT NOT NULL REFERENCES ai_skill_category (id),
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

COMMENT ON TABLE ai_skill_category_bind IS '技能与分类绑定（一技能一类）';

CREATE INDEX IF NOT EXISTS idx_ai_skill_category_bind_cat
    ON ai_skill_category_bind (category_id);

